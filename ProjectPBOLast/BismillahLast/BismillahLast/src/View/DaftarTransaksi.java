    // Aksi tombol Hapus ketika ditekan
    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnHapusActionPerformed
        if (idTransaksi == 0)
            JOptionPane.showMessageDialog(this, "Pilih transaksi yang ingin dihapus terlebih dahulu");
        else {
            int confirm = JOptionPane.showConfirmDialog(this, "Apakah Anda yakin ingin menghapus transaksi ini?", "Confirm Delete Transaction", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                kasirC.hapusTransaksi(idTransaksi); // Hapus transaksi berdasarkan ID
                readTable(); // Refresh tabel
            }
        }
    }// GEN-LAST:event_btnHapusActionPerformed

    // Aksi tombol Detail ketika ditekan
    private void btndetailActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btndetailActionPerformed
        if (idTransaksi == 0)
            JOptionPane.showMessageDialog(this, "Pilih transaksi terlebih dahulu");
        else {
            new DetailTransaksi(modelKasir, kasirC, idTransaksi); // Buka detail transaksi baru
            this.dispose();
        }
    }// GEN-LAST:event_btndetailActionPerformed

    // Aksi tombol Kembali ke MainView
    private void btnKembaliActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnKembaliActionPerformed
        new MainView(modelKasir);
        this.dispose();
    }// GEN-LAST:event_btnKembaliActionPerformed

    // Tambahkan method ini untuk menangkap klik pada tabel
    private void tableMouseClicked(java.awt.event.MouseEvent evt) {// GEN-FIRST:event_tableMouseClicked
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        int row = table.getSelectedRow();
        idTransaksi = Integer.parseInt(model.getValueAt(row, 0).toString());
    }// GEN-LAST:event_tableMouseClicked

