    // Method untuk membaca dan menampilkan data transaksi ke tabel
    public void readTable() {
        String[][] dataTransaksi = kasirC.daftarTransaksi(); // Ambil data transaksi dari controller
        table.setModel(new DefaultTableModel(
                dataTransaksi,
                new String[] {
                        "Trans ID", "Total Product", "Total Price", "Paid", "Change",
                        "Payment Method", "Date",
                        "Cashier"
                }));
        // Format nilai total harga, bayar, dan kembalian dengan format rupiah
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        for (int i = 0; i < dataTransaksi.length; i++) {
            for (int j = 0; j < dataTransaksi[i].length; j++) {
                // jika kolom adalah total harga, bayar, dan kembalian
                if (j == 2 || j == 3 || j == 4) {
                    int value = Integer.parseInt(dataTransaksi[i][j]);
                    model.setValueAt("Rp. " + String.format("%,d", value), i, j);
                } else {
                    model.setValueAt(dataTransaksi[i][j], i, j);
                }
            }
        }
    }

